export type RulesLinkPart = { href: string; label: string };
export type RulesTextPart = string | RulesLinkPart;
export type RulesParagraph = RulesTextPart[];

export type RulesSection = {
  id: string;
  title: string;
  body: RulesParagraph[];
};

export function isRulesLinkPart(p: RulesTextPart): p is RulesLinkPart {
  return typeof p === 'object' && p !== null && 'href' in p && 'label' in p;
}

function line(...parts: RulesTextPart[]): RulesParagraph {
  return parts;
}

